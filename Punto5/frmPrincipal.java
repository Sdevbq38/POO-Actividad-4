    private void bntLeerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntLeerActionPerformed
        // Borrar el contenido de la lectura anterior.
txtContenido.setText("");

String ruta = txtRuta.getText().trim();

// Comprobar que se haya ingresado una ruta.
if (ruta.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Ingrese la ruta del archivo de texto.",
        "Campo vacío",
        JOptionPane.WARNING_MESSAGE
    );

    return;
}

try {
    String contenido = LeerArchivo.leer(ruta);

    txtContenido.setText(contenido);
    txtContenido.setCaretPosition(0);

    if (contenido.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "El archivo se leyó correctamente, pero está vacío.",
            "Archivo vacío",
            JOptionPane.INFORMATION_MESSAGE
        );
    }

} catch (IOException e) {
    JOptionPane.showMessageDialog(
        this,
        "No se pudo leer el archivo.\n"
            + "Verifique la ruta y los permisos de lectura.",
        "Error de lectura",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_bntLeerActionPerformed

