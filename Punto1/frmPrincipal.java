    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        txtResultado.setText("");

try {
    txtRegistro.append("Ingresando al primer try\n");

    double numerador =
        Double.parseDouble(txtNumerador.getText().trim());

    double denominador =
        Double.parseDouble(txtDenominador.getText().trim());

    if (!Double.isFinite(numerador)
            || !Double.isFinite(denominador)) {
        throw new NumberFormatException();
    }

    double cociente =
        PruebaExcepciones.dividir(numerador, denominador);

    txtResultado.setText(String.valueOf(cociente));

    txtRegistro.append("Después de la división\n");

} catch (ArithmeticException e) {
    txtRegistro.append("División por cero\n");

    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Error aritmético",
        JOptionPane.ERROR_MESSAGE
    );

} catch (NumberFormatException e) {
    txtRegistro.append("Entrada no numérica o no válida\n");

    JOptionPane.showMessageDialog(
        this,
        "Ingrese números válidos en ambos campos. "
            + "Use punto para los decimales.",
        "Error de formato",
        JOptionPane.ERROR_MESSAGE
    );

} finally {
    txtRegistro.append("Ingresando al primer finally\n");
}
    }//GEN-LAST:event_btnCalcularActionPerformed

    private void btnObjetoNuloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObjetoNuloActionPerformed
        try {
    txtRegistro.append("Ingresando al segundo try\n");

    String texto = PruebaExcepciones.probarObjetoNulo();

    txtRegistro.append("Imprimiendo objeto: " + texto + "\n");

} catch (ArithmeticException e) {
    txtRegistro.append("División por cero\n");

} catch (Exception e) {
    txtRegistro.append("Ocurrió una excepción\n");

    JOptionPane.showMessageDialog(
        this,
        "Se intentó utilizar un objeto nulo "
            + "(NullPointerException).",
        "Excepción capturada",
        JOptionPane.ERROR_MESSAGE
    );

} finally {
    txtRegistro.append("Ingresando al segundo finally\n");
}
    }//GEN-LAST:event_btnObjetoNuloActionPerformed

