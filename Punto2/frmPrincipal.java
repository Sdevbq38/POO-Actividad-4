    private void btnVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarActionPerformed
        // Borrar los datos del intento anterior.
txtResultado.setText("");

// Leer los campos.
String nombre = txtNombre.getText().trim();
String apellidos = txtApellidos.getText().trim();
String entradaEdad = txtEdad.getText().trim();

// Revisar que todos los campos tengan información.
if (nombre.isEmpty()
        || apellidos.isEmpty()
        || entradaEdad.isEmpty()) {

    JOptionPane.showMessageDialog(
        this,
        "Complete el nombre, los apellidos y la edad.",
        "Campos vacíos",
        JOptionPane.WARNING_MESSAGE
    );

    return;
}

try {
    // Convertir la edad a un número entero.
    int edad = Integer.parseInt(entradaEdad);

    // Crear el vendedor con su nombre y apellidos.
    Vendedor vendedor = new Vendedor(nombre, apellidos);

    // Verificar y asignar la edad.
    vendedor.verificarEdad(edad);

    // Mostrar los datos únicamente si la edad es válida.
    txtResultado.setText(vendedor.imprimir());

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this,
        "La edad debe ser un número entero válido.",
        "Error de formato",
        JOptionPane.ERROR_MESSAGE
    );

} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Edad no válida",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnVerificarActionPerformed

