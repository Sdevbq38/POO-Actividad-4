    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        try {
    equipo = new EquipoMaratonProgramacion(
        txtEquipo.getText(),
        txtUniversidad.getText(),
        txtLenguaje.getText()
    );

    txtResultado.setText(equipo.mostrarDatos());

    // Conservar los datos del equipo creado.
    txtEquipo.setEditable(false);
    txtUniversidad.setEditable(false);
    txtLenguaje.setEditable(false);

    btnCrear.setEnabled(false);
    btnAnadir.setEnabled(true);
    btnVerificar.setEnabled(true);

    txtNombre.requestFocusInWindow();

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Error al crear equipo",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnCrearActionPerformed

