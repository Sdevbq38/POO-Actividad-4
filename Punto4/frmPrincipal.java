    private void btnAnadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnadirActionPerformed
        try {
    if (equipo == null) {
        throw new Exception(
            "Primero debe crear el equipo."
        );
    }

    if (equipo.estaLleno()) {
        throw new Exception(
            "El equipo ya está completo. "
                + "No se pudo agregar el programador."
        );
    }

    Programador programador = new Programador(
        txtNombre.getText(),
        txtApellidos.getText()
    );

    equipo.anadir(programador);

    txtResultado.setText(equipo.mostrarDatos());

    // Preparar los campos para el siguiente integrante.
    txtNombre.setText("");
    txtApellidos.setText("");
    txtNombre.requestFocusInWindow();

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Error al añadir programador",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAnadirActionPerformed

    private void btnVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarActionPerformed
        try {
    if (equipo == null) {
        throw new Exception(
            "Primero debe crear el equipo."
        );
    }

    if (equipo.getTamanoEquipo() < 2) {
        throw new Exception(
            "El equipo debe tener mínimo dos programadores."
        );
    }

    JOptionPane.showMessageDialog(
        this,
        "El equipo cumple el requisito "
            + "de tener entre dos y tres integrantes.",
        "Equipo válido",
        JOptionPane.INFORMATION_MESSAGE
    );

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Equipo no válido",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnVerificarActionPerformed

